const SUPPORTED_LANGS = ["en", "de"];
let LANG = SUPPORTED_LANGS.includes(localStorage.getItem("ui-lang")) ? localStorage.getItem("ui-lang") : "en";

function t(key, params = {}) {
  const s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

/** Server messages are either "error.key", "error.key: detail" or plain text from older versions. */
function translateMessage(msg) {
  const m = /^(error\.[a-z_]+)(?::\s*([\s\S]*))?$/.exec(String(msg ?? ""));
  if (!m || !(m[1] in I18N.en)) return msg;
  return m[2] ? `${t(m[1])}: ${m[2]}` : t(m[1]);
}

function applyStaticI18n(root = document) {
  document.documentElement.lang = LANG;
  document.title = t("app.title");
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  });
}
